const CapabilityStrip = ({ items, build }) => {
  const resolvedItems = (items && items.length > 0)
    ? items
    : (build?.systemDesign?.bullets || []).map((b, i) => ({
        title: b.text,
        icon: ['user', 'workflow', 'automation', 'analytics'][i % 4]
      }));

  if (!resolvedItems || resolvedItems.length === 0) return null;

  return (
    <div className="capability-strip-container">
      <div className="capability-strip-inner">
        {resolvedItems.map((item, idx) => (
          <div key={idx} className="capability-strip-item">
            <div className="capability-icon-box">
              <CapabilityIcon name={item.icon} />
            </div>
            <span className="capability-strip-label">{item.title}</span>
          </div>
        ))}
      </div>
    </div>
  );
};

export default CapabilityStrip;
